            ['=', 'ay', 'AI'],
            ['=', 'ey', 'AI'],
            ['=', 'ei', 'AI'],
            ['=', 'oi', 'OI'],
            ['=', 'oy', 'OI'],
            ['=', 'ew', 'U'],
            ['~', '([aeiouyAIOU][^aeiouyAIOU]+)aje$', '\1Ij'],
            ['~', '(?:[iy]([bdfgjklmnprstvG]l?)|a([bdfgjklmnpstvG]l?|st|nj))e(s?)$', 'AI\1\2\3'],
