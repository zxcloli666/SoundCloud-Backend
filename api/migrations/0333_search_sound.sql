            ['=', 'move', 'mUv'],
            ['=', 'prove', 'prUv'],
            ['=', 'imagine', 'imajin'],
            ['=', 'machine', 'majin'],
            ['=', 'engine', 'enjin'],
            ['=', 'office', 'ofis'],
            ['=', 'service', 'servis'],
            ['=', 'police', 'polis'],
            ['=', 'album', 'albom'],
            ['=', 'girl', 'Gerl'],
            ['=', 'bird', 'berd'],
            ['=', 'first', 'ferst'],
            ['=', 'dirty', 'derty'],
            ['=', 'burn', 'bern'],
            ['=', 'turn', 'tern'],
            ['=', 'hurt', 'hert'],
            ['=', 'eye', 'AI'],
            ['=', 'bye', 'bAI'],
            ['=', 'uy', 'AI'],
            ['=', 'you', 'iU'],
            ['=', 'new', 'niU'],
            ['=', 'view', 'viU'],
