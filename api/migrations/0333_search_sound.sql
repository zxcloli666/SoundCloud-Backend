            ['=', 'touch', 'tAj'],
            ['=', 'young', 'iAng'],
            ['=', 'ouble', 'Abl'],
            ['=', 'ountr', 'Antr'],
            ['=', 'ould', 'Ud'],
            ['=', 'heart', 'hart'],
            ['=', 'head', 'hed'],
            ['=', 'dead', 'ded'],
            ['=', 'death', 'det'],
            ['=', 'heav', 'hev'],
            ['=', 'earth', 'ert'],
            ['=', 'ready', 'redy'],
            ['=', 'money', 'mAny'],
            ['=', 'monkey', 'mAnky'],
            ['=', 'honey', 'hAny'],
            ['=', 'other', 'Ater'],
