    END IF;
    FOREACH rule SLICE 1 IN ARRAY rules LOOP
        heard := CASE rule[1]
            WHEN '~' THEN regexp_replace(heard, rule[2], rule[3], 'g')
            WHEN ':' THEN translate(heard, rule[2], rule[3])
            ELSE replace(heard, rule[2], rule[3])
        END;
    END LOOP;
    heard := regexp_replace(lower(translate(heard, 'ey', 'ai')), 'h(?![aiou])', '', 'g');
    RETURN regexp_replace(heard, '(.)\1+', '\1', 'g');
END
