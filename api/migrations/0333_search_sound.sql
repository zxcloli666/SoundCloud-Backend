    LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE
AS $$
DECLARE
    heard text := lower(word);
    rules text[];
    rule text[];
BEGIN
    IF heard ~ '[а-яёіїєґ]' THEN
        rules := ARRAY[
            ['~', '[^а-яёіїєґa-z0-9]', ''],
            ['=', 'дж', 'j'],
            ['=', 'шт', 'st'],
            ['=', 'шп', 'sp'],
            ['~', '[ьъ](?=[еэ])', 'i'],
            ['~', '(^|[аеёиоуыэюяьъ])(?=[яю])|^(?=е)', '\1i'],
            ['~', '(^|к)у(?=[аеиоэы])', '\1v'],
            ['=', 'ей', 'ai'],
            ['=', 'эй', 'ai'],
            ['=', 'ай', 'ai'],
            ['=', 'ой', 'oi'],
            ['=', 'ау', 'au'],
            ['=', 'оу', 'au'],
            [':', 'абвгдеёжзийклмнопрстуфхцчшщыэюяіїєґъь', 'abvgdaajsiiklmnoprstufhsjjjiauaiiag'],
            ['=', 'ts', 's'],
            ['=', 'tj', 'j'],
            ['=', 'dj', 'j']
        ];
    ELSE
        rules := ARRAY[
            ['~', '[^a-z0-9]', ''],
            ['=', 'x', 'ks'],
            ['=', 'people', 'pIpl'],
            ['=', 'friend', 'frend'],
            ['=', 'great', 'grAIt'],
            ['=', 'break', 'brAIk'],
            ['=', 'michael', 'mAIkl'],
            ['=', 'rihanna', 'riana'],
            ['=', 'yonce', 'ionsA'],
            ['=', 'geor', 'jor'],
            ['=', 'gucci', 'gUji'],
