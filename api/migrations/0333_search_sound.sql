            ['=', 'geek', 'Geek'],
            ['=', 'kno', 'no'],
            ['=', 'kni', 'ni'],
            ['=', 'knee', 'nee'],
            ['=', 'wr', 'r'],
            ['=', 'eigh', 'AI'],
            ['=', 'igh', 'AI'],
            ['=', 'ought', 'Ot'],
            ['=', 'gh', ''],
            ['=', 'tsch', 'j'],
            ['=', 'tch', 'j'],
            ['~', 'sch(?=[^aeiouy]|$)', 'j'],
            ['=', 'sch', 'sk'],
            ['=', 'sh', 'j'],
